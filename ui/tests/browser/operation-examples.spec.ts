import {test,expect} from "./tool-host";
import {readFile,readdir,rm} from "node:fs/promises";
import {join,dirname} from "node:path";
import {openOptionalSettings} from "./sample-input";
test.describe("owned operation examples",()=>{
 test.use({hostScenario:"v04-operations"});
 test("a native example restores after deleting its source runs and runs only its edited action",async({page,host})=>{
  await host.open(page);await page.getByRole("button",{name:"Workspace Playground",exact:true}).click();
  await page.getByRole("dialog",{name:"Choose workspace"}).getByRole("button",{name:new RegExp("^Operations ")}).click();
  await page.getByLabel("Import image",{exact:true}).setInputFiles("tests/fixtures/sample.png");
  await expect(page.getByText(/Image ·/)).toBeVisible();await page.getByRole("button",{name:"Run",exact:true}).click();
  await page.getByRole("button",{name:"Use marker item 1 in another action",exact:true}).click();
  await page.getByRole("dialog",{name:"Send artifact to"}).getByRole("button",{name:/stamp marker.*marker/}).click();
  await page.getByRole("combobox",{name:"Saved image",exact:true}).selectOption({index:1});
  await page.getByRole("button",{name:"Run",exact:true}).click();
  await page.getByRole("button",{name:"Use token item 1 in another action",exact:true}).click();
  await page.getByRole("dialog",{name:"Send artifact to"}).getByRole("button",{name:/soften token.*token/}).click();
  await page.getByRole("button",{name:"Run",exact:true}).click();
  await expect(page.getByRole("region",{name:"Native preservation"})).toContainText("Native artifacts · preserved");
  await page.getByRole("button",{name:"Examples",exact:true}).click();
  const examples=page.getByRole("dialog",{name:"Examples",exact:true});
  await examples.getByLabel("Example name",{exact:true}).fill("Reusable soften");
  await examples.getByRole("button",{name:"Save example",exact:true}).click();
  await expect(examples.getByRole("button",{name:"Open Reusable soften",exact:true})).toBeVisible();
  await examples.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("button",{name:"Clean up library",exact:true}).click();
  const cleanup=page.getByRole("dialog",{name:"Clean up library",exact:true});
  const runs=cleanup.getByLabel(/Delete run/);await expect(runs).toHaveCount(3);
  for(let i=0;i<3;i++)await runs.nth(i).check();
  await cleanup.getByRole("button",{name:"Preview cleanup"}).click();
  await cleanup.getByRole("button",{name:"Confirm cleanup"}).click();
  await expect(cleanup.getByRole("status")).toContainText("Cleanup complete");
  await host.stop();await rm(join(dirname(host.root),"tool/artifacts"),{recursive:true});await host.start();await host.open(page);
  await page.getByRole("button",{name:"Examples",exact:true}).click();
  await examples.getByRole("button",{name:"Open Reusable soften",exact:true}).click();
  const restore=page.getByRole("dialog",{name:"Restore saved artifact"});
  await expect(restore).toContainText("Verified native bytes");
  await restore.getByRole("button",{name:"Import saved copy",exact:true}).click();
  await expect(page.getByRole("region",{name:"Result",exact:true})).toContainText("Example loaded: Reusable soften");
  await openOptionalSettings(page);
  await page.getByLabel("Amount",{exact:true}).fill("0.5");
  await page.getByRole("button",{name:"Run",exact:true}).click();
  await expect(page.getByText("Contract evidence: complete.",{exact:false})).toBeVisible();
  const runRoot=join(dirname(host.root),"tool/runs");
  const records=await Promise.all((await readdir(runRoot)).map(async id=>JSON.parse(await readFile(join(runRoot,id,"run.json"),"utf8"))));
  expect(records).toHaveLength(4);
  expect(records.filter(record=>record.action==="locate_marker")).toHaveLength(1);
  expect(records.filter(record=>record.action==="stamp_marker")).toHaveLength(1);
  expect(records.filter(record=>record.action==="soften_token")).toHaveLength(2);
  expect(records.some(record=>record.invocation?.arguments.amount===0.5)).toBe(true);
 });
});
test("workspace-dependent examples require an explicit checkbox",async({page})=>{
 await page.goto("http://127.0.0.1:6006/iframe.html?id=workspace-examples--partial-confirmation&viewMode=story");
 await page.getByLabel("Example name",{exact:true}).fill("Depends on tool store");
 await page.getByRole("button",{name:"Save example",exact:true}).click();
 await expect(page.getByRole("alert")).toContainText("Confirm saving a workspace-dependent example");
 await page.getByRole("checkbox",{name:/Allow a workspace-dependent/}).check();
 await page.getByRole("button",{name:"Save example",exact:true}).click();
 await expect(page.getByRole("status")).toContainText("Saved as workspace-dependent");
 await expect(page.getByRole("checkbox",{name:/Allow a workspace-dependent/})).not.toBeChecked();
});
